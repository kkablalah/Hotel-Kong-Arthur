-- 01_schema.sql: struktur for hotellets leverede data (tabeller og views), ingen data.
-- Konverteret fra MySQL Workbench-eksporten (MySQL 8.0.44) til PostgreSQL.
-- MySQL-originalen ligger i commit ba5bd83.
--
-- Oversaettelse:
-- - unsigned findes ikke i PostgreSQL. Derfor integer og CHECK, hvor negative tal skal afvises.
-- - AUTO_INCREMENT er blevet til identity. BY DEFAULT tillader de faste id'er i 02_data.sql.
-- - enum er blevet til varchar med CHECK.
-- - Fremmednoegler faar egne indekser, fordi PostgreSQL ikke opretter dem selv, som MySQL goer.

--
-- Tabeller
--

CREATE TABLE countries (
  country_id integer GENERATED BY DEFAULT AS IDENTITY,
  name varchar(64) NOT NULL,
  PRIMARY KEY (country_id),
  UNIQUE (name)
);

CREATE TABLE drink_categories (
  category_id integer GENERATED BY DEFAULT AS IDENTITY,
  name varchar(40) NOT NULL,
  PRIMARY KEY (category_id),
  UNIQUE (name)
);

CREATE TABLE drinks (
  drink_id integer GENERATED BY DEFAULT AS IDENTITY,
  name varchar(80) NOT NULL,
  category_id integer NOT NULL,
  price_dkk numeric(8,2) NOT NULL,
  units_sold integer NOT NULL DEFAULT 0,
  PRIMARY KEY (drink_id),
  UNIQUE (name),
  CONSTRAINT fk_drinks_category FOREIGN KEY (category_id) REFERENCES drink_categories (category_id),
  CONSTRAINT chk_drinks_price CHECK (price_dkk >= 0),
  CONSTRAINT chk_drinks_units CHECK (units_sold >= 0)
);
CREATE INDEX fk_drinks_category ON drinks (category_id);

CREATE TABLE room_types (
  room_type_id integer GENERATED BY DEFAULT AS IDENTITY,
  name varchar(40) NOT NULL,
  PRIMARY KEY (room_type_id),
  UNIQUE (name)
);

CREATE TABLE stays (
  stay_id integer GENERATED BY DEFAULT AS IDENTITY,
  first_name varchar(60) NOT NULL,
  family_name varchar(60) NOT NULL,
  country_id integer NOT NULL,
  room_type_id integer NOT NULL,
  days_rented integer NOT NULL,
  season varchar(4) NOT NULL,
  price numeric(12,2) NOT NULL,
  PRIMARY KEY (stay_id),
  CONSTRAINT fk_stays_country FOREIGN KEY (country_id) REFERENCES countries (country_id),
  CONSTRAINT fk_stays_room_type FOREIGN KEY (room_type_id) REFERENCES room_types (room_type_id),
  CONSTRAINT chk_stays_days CHECK (days_rented >= 1),
  CONSTRAINT chk_stays_price CHECK (price >= 0),
  CONSTRAINT chk_stays_season CHECK (season IN ('low', 'mid', 'high'))
);
CREATE INDEX fk_stays_country ON stays (country_id);
CREATE INDEX fk_stays_room_type ON stays (room_type_id);
COMMENT ON COLUMN stays.price IS 'currency not stated in source file';

--
-- Views (oprettes efter tabellerne)
--

CREATE VIEW drink_sales AS
SELECT d.drink_id AS drink_id,
       d.name AS drink,
       c.name AS category,
       d.price_dkk AS price_dkk,
       d.units_sold AS units_sold,
       round(d.price_dkk * d.units_sold, 2) AS revenue_dkk
FROM drinks d
JOIN drink_categories c ON c.category_id = d.category_id;

CREATE VIEW stays_detailed AS
SELECT s.stay_id AS stay_id,
       s.first_name AS first_name,
       s.family_name AS family_name,
       c.name AS country,
       r.name AS room_type,
       s.days_rented AS days_rented,
       s.season AS season,
       s.price AS price
FROM stays s
JOIN countries c ON c.country_id = s.country_id
JOIN room_types r ON r.room_type_id = s.room_type_id;
