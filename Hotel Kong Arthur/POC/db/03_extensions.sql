-- room_number er integer, fordi testene bruger numre fra 60000, som smallint ikke kan rumme.
CREATE TABLE rooms (
  room_id integer GENERATED BY DEFAULT AS IDENTITY,
  room_number integer NOT NULL,
  room_type_id integer NOT NULL,
  capacity smallint NOT NULL,
  is_active boolean NOT NULL DEFAULT TRUE,
  PRIMARY KEY (room_id),
  UNIQUE (room_number),
  CONSTRAINT fk_rooms_room_type FOREIGN KEY (room_type_id) REFERENCES room_types (room_type_id),
  CONSTRAINT chk_rooms_number CHECK (room_number >= 0),
  CONSTRAINT chk_rooms_capacity CHECK (capacity BETWEEN 1 AND 4)
);
CREATE INDEX fk_rooms_room_type ON rooms (room_type_id);

-- Tidspunkter er uden tidszone og med hele sekunder, som kontraktens YYYY-MM-DD HH:MM:SS.
CREATE TABLE bookings (
  booking_id integer GENERATED BY DEFAULT AS IDENTITY,
  room_id integer NOT NULL,
  first_name varchar(60) NOT NULL,
  family_name varchar(60) NOT NULL,
  country_id integer NULL,
  guest_count smallint NOT NULL,
  check_in_date date NOT NULL,
  check_out_date date NOT NULL,
  total_price numeric(12,2) NOT NULL,
  created_at timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (booking_id),
  CONSTRAINT fk_bookings_room FOREIGN KEY (room_id) REFERENCES rooms (room_id),
  CONSTRAINT fk_bookings_country FOREIGN KEY (country_id) REFERENCES countries (country_id),
  CONSTRAINT chk_bookings_guest_count CHECK (guest_count BETWEEN 1 AND 4),
  CONSTRAINT chk_bookings_dates CHECK (check_in_date < check_out_date),
  CONSTRAINT chk_bookings_price CHECK (total_price > 0)
);
CREATE INDEX fk_bookings_room ON bookings (room_id);
CREATE INDEX fk_bookings_country ON bookings (country_id);
COMMENT ON COLUMN bookings.country_id IS 'NULL vises som Ukendt (AC-08.4)';
COMMENT ON COLUMN bookings.guest_count IS 'Graensen for det enkelte vaerelse tjekkes i business-laget (FR-01)';
COMMENT ON COLUMN bookings.total_price IS 'DKK inkl. skatter og gebyrer (BR-02)';

-- PostgreSQL har ikke ON UPDATE CURRENT_TIMESTAMP fra MySQL. Derfor en trigger.
-- Ligesom i MySQL flyttes tidspunktet kun, hvis rækken faktisk ændres.
CREATE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER bookings_set_updated_at
BEFORE UPDATE ON bookings
FOR EACH ROW WHEN (OLD.* IS DISTINCT FROM NEW.*) EXECUTE FUNCTION set_updated_at();

CREATE TABLE customer_satisfaction (
  satisfaction_id integer GENERATED BY DEFAULT AS IDENTITY,
  booking_id integer NOT NULL,
  rating smallint NOT NULL,
  comment varchar(500) NULL,
  created_at timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (satisfaction_id),
  CONSTRAINT fk_satisfaction_booking FOREIGN KEY (booking_id) REFERENCES bookings (booking_id) ON DELETE CASCADE,
  CONSTRAINT chk_satisfaction_rating CHECK (rating BETWEEN 1 AND 5)
);
CREATE INDEX fk_satisfaction_booking ON customer_satisfaction (booking_id);
