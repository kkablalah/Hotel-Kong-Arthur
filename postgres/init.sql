CREATE TABLE IF NOT EXISTS bookings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  guest_name VARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL,
  room_number INTEGER NOT NULL CHECK (room_number > 0),
  check_in DATE NOT NULL,
  check_out DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'confirmed'
    CHECK (status IN ('confirmed', 'cancelled', 'checked_in', 'checked_out')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT bookings_check_out_after_check_in CHECK (check_out > check_in)
);

CREATE INDEX IF NOT EXISTS idx_bookings_room_number ON bookings (room_number);
CREATE INDEX IF NOT EXISTS idx_bookings_status ON bookings (status);
CREATE INDEX IF NOT EXISTS idx_bookings_dates ON bookings (check_in, check_out);

-- Imported hotel stays are source records, not browser bookings. Their source
-- workbook has no booking dates or room numbers.
CREATE TABLE IF NOT EXISTS hotel_stays (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_file TEXT NOT NULL,
  source_sheet TEXT NOT NULL,
  source_row INTEGER NOT NULL CHECK (source_row > 1),
  first_name TEXT NOT NULL,
  family_name TEXT NOT NULL,
  country TEXT NOT NULL,
  room_type TEXT NOT NULL,
  days_rented INTEGER NOT NULL,
  season TEXT NOT NULL,
  price NUMERIC NOT NULL,
  raw_values JSONB NOT NULL,
  CONSTRAINT hotel_stays_source_row_unique UNIQUE (source_file, source_sheet, source_row)
);

CREATE TABLE IF NOT EXISTS drink_products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_file TEXT NOT NULL,
  source_sheet TEXT NOT NULL,
  source_row INTEGER NOT NULL CHECK (source_row > 1),
  drink_name TEXT NOT NULL,
  category TEXT NOT NULL,
  price NUMERIC NOT NULL,
  units_sold INTEGER NOT NULL,
  raw_values JSONB NOT NULL,
  CONSTRAINT drink_products_source_row_unique UNIQUE (source_file, source_sheet, source_row)
);
